import pandas as pd
import re

def deep_clean_ai_review(text: str) -> str:
    """
    Hàm dọn dẹp sâu: Xóa văn mẫu kịch tính, placeholder và định dạng rập khuôn của AI.
    """
    patterns = [
        # 1. XÓA CÁC CÂU CẢM THÁN "KỊCH TÍNH" CỦA AI (Xóa đến hết câu chứa dấu chấm)
        # Bắt các câu bắt đầu bằng "I must say,", "I am astonished", "I am underwhelmed"...
        r"(?i)(I must say,\s*)?(I am|I'm)\s*(underwhelmed|astonished|surprised)[^\.]*\.\s*",

        # 2. XÓA PLACEHOLDER
        # Cắt các dòng "Paper Title: [Insert Paper Title]"
        r"(?i)(Paper Title|Authors):\s*\[Insert.*?\].*\n*",
        # Cắt các cụm [Insert...] nằm rải rác
        r"\[Insert.*?\]",

        # 3. XÓA CÁC TIÊU ĐỀ RẬP KHUÔN (Để text trông giống 1 đoạn văn tự nhiên hơn)
        # Bắt các từ như Summary:, Strengths:, Weaknesses:, v.v. đứng đầu dòng
        r"(?i)^(Summary|Overall Assessment|Overall Impression|Strengths|Weaknesses and Suggestions for Improvement|Weaknesses and Suggestions|Minor Comments|Conclusion|Recommendation|Specific Comments|Actionable Suggestions):\s*\n*",

        # 4. Xóa từ Peer Review
        r"\bPeer Review\b",

        # 5. XÓA ĐÁNH SỐ (1. 2. 3.), BULLETS (*, -) VÀ TIÊU ĐỀ PHỤ
        # Sẽ bắt các dạng:
        # "1. Novel Architecture: The model..." -> xóa "1. Novel Architecture: "
        # "* Lack of Ablation: The authors..." -> xóa "* Lack of Ablation: "
        # "2. The results are good." -> xóa "2. "
        r"^[ \t]*(?:\d+\.|\*|\-)\s*(?:[^:\n]+:\s*)?"
    ]

    cleaned_text = str(text)

    # Quét và xóa
    for pattern in patterns:
        # Dùng re.MULTILINE để có thể bắt được các Regex có dấu ^ (đầu dòng)
        cleaned_text = re.sub(pattern, "", cleaned_text, flags=re.IGNORECASE | re.MULTILINE)

    # 4. FIX LỖI CỤT ĐUÔI (Cắt bỏ phần text lở dở ở cuối nếu API sinh thiếu)
    last_punct_idx = max(cleaned_text.rfind('.'), cleaned_text.rfind('!'), cleaned_text.rfind('?'))
    if last_punct_idx != -1:
        cleaned_text = cleaned_text[:last_punct_idx + 1]

    # Xóa các khoảng trắng thừa do việc cắt text để lại
    cleaned_text = re.sub(r'\n{3,}', '\n\n', cleaned_text)

    return cleaned_text.strip()

