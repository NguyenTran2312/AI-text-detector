# --- Yêu cầu 1: Làm sạch dữ liệu văn bản (Advanced Text Cleaning với Regex) ---
def clean_text(text):
    text = str(text) # Đảm bảo text là kiểu chuỗi để tránh lỗi

    # Bước 1. Truncation (Cắt bỏ phần đuôi bài viết)
    # Các từ khóa: "References", "External links", "See also", "Further reading", "Bibliography".
    # Điều kiện: Các từ này phải đứng ở đầu một dòng (có thể có ký tự khoảng trắng hoặc dấu markdown).
    # Hành động: Xóa tiêu đề đó và toàn bộ phần văn bản từ đó cho đến cuối chuỗi.
    truncation_keywords = [
        'References', 'External links', 'See also',
        'Further reading', 'Bibliography'
    ]
    # Xây dựng pattern regex để tìm bất kỳ từ khóa nào ở đầu dòng
    # ^\s*[=\-#*]*\s* : Khớp với khoảng trắng, dấu markdown (==, ###, *) ở đầu dòng.
    # (?:...) : Nhóm không bắt giữ cho các từ khóa.
    # \b : Biên từ, đảm bảo khớp toàn bộ từ khóa chứ không phải một phần.
    truncation_pattern = r'^\s*[=\-#*]*\s*(?:' + '|'.join(re.escape(k) for k in truncation_keywords) + r')\b'

    # Tìm kiếm sự xuất hiện sớm nhất của pattern này (case-insensitive, multi-line)
    match = re.search(truncation_pattern, text, flags=re.IGNORECASE | re.MULTILINE)
    if match:
        # Nếu tìm thấy, cắt bỏ phần văn bản từ vị trí bắt đầu của match trở đi
        text = text[:match.start()]

    # Bước 2. Line Removal (Xóa các dòng/đoạn rác cụ thể)
    # Các từ khóa: "Edit:", "ETA:", "TL;DR", "Tips:", "Warnings:", "Notes:".
    # Điều kiện: Chỉ bắt khi các từ này nằm ở ngay đầu dòng.
    # Hành động: Xóa từ khóa đó và nội dung trên cùng dòng/đoạn đó.
    line_removal_keywords = [
        'Edit:', 'ETA:', 'TL;DR', 'Tips:', 'Warnings:', 'Notes:'
    ]
    # Xây dựng pattern regex để tìm các từ khóa này ở đầu dòng và sau đó khớp toàn bộ dòng
    # ^\s* : Khớp với khoảng trắng ở đầu dòng.
    # (?:...) : Nhóm không bắt giữ cho các từ khóa.
    # .*$ : Khớp bất kỳ ký tự nào cho đến cuối dòng (không bao gồm ký tự xuống dòng).
    line_removal_pattern = r'^\s*(?:' + '|'.join(re.escape(k) for k in line_removal_keywords) + r').*$'
    text = re.sub(line_removal_pattern, '', text, flags=re.IGNORECASE | re.MULTILINE)

    # Bước 3. Xóa HTML/CSS rác
    # Xóa các chuỗi định dạng CSS inline rác như "styleborderleftpx..." và các thẻ HTML thừa nếu có.
    # Xóa các chuỗi CSS inline rác cụ thể (ví dụ: 'styleborderleftpx...')
    # styleborderleftpx[^\s]* : Khớp 'styleborderleftpx' theo sau bởi bất kỳ ký tự nào không phải khoảng trắng.
    text = re.sub(r'styleborderleftpx[^\s]*', '', text, flags=re.IGNORECASE)
    # Xóa các thuộc tính 'style="..."' hoặc 'style=\'...\''
    # style\s*=\s*"[^"]*" : Khớp thuộc tính style với giá trị trong dấu ngoặc kép.
    text = re.sub(r'style\s*=\s*"[^"]*"', '', text, flags=re.IGNORECASE)
    # style\s*=\s*\'[^\']*\'' : Khớp thuộc tính style với giá trị trong dấu ngoặc đơn.
    text = re.sub(r'style\s*=\s*\'[^\']*\'', '', text, flags=re.IGNORECASE)
    # Xóa các thẻ HTML chung
    # <[^>]+> : Khớp bất kỳ chuỗi nào bắt đầu bằng '<', theo sau là một hoặc nhiều ký tự không phải '>', và kết thúc bằng '>'.
    text = re.sub(r'<[^>]+>', '', text)

    return text.strip()

